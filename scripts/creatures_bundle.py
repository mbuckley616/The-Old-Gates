#!/usr/bin/env python3
"""Make the classic-script copy of the creature kit that the new look loads (Session 1202, card F4: the wolves as plans).

The kit (docs/prototypes/levelup/creatures.js, the bodies builder's) is an ES module that imports three and two of three's
addons (BufferGeometryUtils' mergeGeometries, ImprovedNoise). The game is plain classic scripts that a downloaded folder opens
by double-clicking, so no modules. This writes vendor/creatures.builder.js: the two addons inlined from the copies the
prototypes vendor (docs/prototypes/levelup/vendor/addons/), each in a scope of its own binding only what the kit imports, then
creatures.js inside one function that returns its exports as `HC` (window.HC). The new look loads it after
vendor/people.builder.js (index.html's chooser).

  python3 scripts/creatures_bundle.py           writes vendor/creatures.builder.js
  python3 scripts/creatures_bundle.py --check   exits 1 if vendor/creatures.builder.js is not what creatures.js makes now

The copy is generated, never edited by hand: a change to creatures.js reaches the game when this is run again."""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from people_bundle import export_names, strip_exports  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'docs', 'prototypes', 'levelup', 'creatures.js')
ADDONS = os.path.join(ROOT, 'docs', 'prototypes', 'levelup', 'vendor', 'addons')
OUT = os.path.join(ROOT, 'vendor', 'creatures.builder.js')
THREE_STAR = "import * as THREE from 'three';\n"
ADDON = re.compile(r"^import \{ ([\w, ]+) \} from 'three/addons/([\w/.-]+\.js)';\n", re.M)


def addon(rel, binds):
    """One of three's addons inlined in its own scope: its named imports from three read off THREE, the names the kit imports returned."""
    path = os.path.join(ADDONS, rel)
    src = open(path, encoding='utf-8').read()
    imps = re.findall(r"^import \{([^}]*)\} from 'three';\n", src, flags=re.M)
    src = re.sub(r"^import \{([^}]*)\} from 'three';\n", '', src, flags=re.M)
    if re.search(r'^import ', src, flags=re.M): sys.exit(f'{rel} imports something besides three')
    names = [n.strip() for n in ','.join(imps).split(',') if n.strip()]
    if any(' as ' in n for n in names): sys.exit(f'{rel}: an aliased import from three')
    src = re.sub(r'^export \{[^}]*\};?\n?', '', src, flags=re.M)
    src = re.sub(r'^export (class|function|const) ', r'\1 ', src, flags=re.M)
    if re.search(r'^export ', src, flags=re.M): sys.exit(f'{rel}: an export this script does not know how to strip')
    want = [b.strip() for b in binds.split(',')]
    if any(' as ' in w for w in want): sys.exit(f'creatures.js imports {binds} from {rel} under another name')
    head = f"const {{ {', '.join(names)} }} = THREE;\n" if names else ''
    return (f'// ── three/addons/{rel}, inlined (its own scope) ──\n'
            f"const {{ {', '.join(want)} }} = (function(){{\n{head}{src}\nreturn {{ {', '.join(want)} }};\n}})();\n")


def bundle(src):
    adds = ADDON.findall(src)
    src = ADDON.sub('', src)
    if src.count(THREE_STAR) != 1 or len(re.findall(r'^import ', src, flags=re.M)) != 1:
        sys.exit('creatures.js imports something besides three and its addons; the bundle would need it too')
    src = src.replace(THREE_STAR, '')
    if re.search(r'\bawait\b|\bfetch\(', src): sys.exit('creatures.js awaits or fetches something')
    names = export_names(src)
    body = ''.join(addon(rel, b) for b, rel in adds) + strip_exports(src, 'creatures.js')
    head = ('// GENERATED by scripts/creatures_bundle.py from docs/prototypes/levelup/creatures.js (Session 1202, card F4). Do not edit:\n'
            '// change creatures.js and run the script again. The new look only (index.html\'s chooser loads it after three.js 0.170).\n'
            "var HC=(function(){'use strict';\n")
    return head + body + '\nreturn {' + ','.join(names) + '};\n})();\n'


def main():
    out = bundle(open(SRC, encoding='utf-8').read())
    if '--check' in sys.argv[1:]:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if out != have: sys.exit('vendor/creatures.builder.js is stale: run python3 scripts/creatures_bundle.py')
        print('vendor/creatures.builder.js matches creatures.js'); return
    open(OUT, 'w', encoding='utf-8', newline='\n').write(out)
    print(f'vendor/creatures.builder.js: {len(out):,} bytes')


if __name__ == '__main__':
    main()
