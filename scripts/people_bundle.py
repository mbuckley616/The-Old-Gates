#!/usr/bin/env python3
"""Make the classic-script copies of the people's builder that the new look loads (Session 1193, card F4).

The builder (docs/prototypes/levelup/people.js, the bodies builder's) is an ES module that fetches MakeHuman's pack
(mh_pack.py's mh/pack.json and mh/pack.bin). The game is plain classic scripts that a downloaded folder opens by
double-clicking, so no modules and no fetch over file://. This writes two files, both loaded only on the new look
(index.html's chooser writes their tags after three.js 0.170's):

  vendor/people.builder.js   people.js inside one function that returns its exports as `HB` (window.HB). Its one
                             fetch is replaced by a read of MH_PACK; loadPack becomes synchronous.
  vendor/mh-pack.js          `var MH_PACK={ix:{…},b64:'…'}`: the pack's index and its binary, base64.

  python3 scripts/people_bundle.py              writes vendor/people.builder.js (and vendor/mh-pack.js if the pack is built)
  python3 scripts/people_bundle.py --pack DIR   takes the pack from DIR (default docs/prototypes/levelup/mh, which
                                                `python3 docs/prototypes/levelup/mh_pack.py` makes; it is not committed)
  python3 scripts/people_bundle.py --check      exits 1 if vendor/people.builder.js is not what people.js makes now

The builder's copy is generated, never edited by hand: a change to people.js reaches the game when this is run again.
The pack changes only when mh_pack.py does (it reads MakeHuman's own files), so --check leaves it alone; its SHA-256
is written into the builder's copy and the game checks it at load."""
import base64, hashlib, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'docs', 'prototypes', 'levelup', 'people.js')
OUT = os.path.join(ROOT, 'vendor', 'people.builder.js')
PACK_OUT = os.path.join(ROOT, 'vendor', 'mh-pack.js')

FETCH = re.compile(r"^export async function loadPack\(base = 'mh/'\) \{\n  const \[ix, buf\] = await Promise\.all\(\[fetch\(.*\n", re.M)


def bundle(src, pack_sha):
    if src.count("import * as THREE from 'three';\n") != 1 or len(re.findall(r'^import ', src, flags=re.M)) != 1:
        sys.exit('people.js imports something besides three; the bundle would need it too')
    src = src.replace("import * as THREE from 'three';\n", '')
    if len(FETCH.findall(src)) != 1:
        sys.exit("people.js's loadPack has changed; cannot replace its fetch")
    src = FETCH.sub("function loadPack() {\n  if (PACK) return PACK; const ix = MH_PACK.ix, buf = mhBuffer();\n", src)
    if re.search(r'\bawait\b|\bfetch\(', src):
        sys.exit('people.js awaits or fetches something besides the pack')
    names = ['loadPack']
    for m in re.finditer(r'^export (?:async )?function (\w+)', src, flags=re.M): names.append(m.group(1))
    for m in re.finditer(r'^export \{ ([\w, ]+) \};$', src, flags=re.M): names += [n.strip() for n in m.group(1).split(',')]
    for m in re.finditer(r'^export const (.*)$', src, flags=re.M):
        # `export const A = …, B = …;` on one line: the names at depth 0 before each `=`
        line, depth, tok, k = m.group(1), 0, '', 0
        at = [0]
        for i, ch in enumerate(line):
            if ch in '([{': depth += 1
            elif ch in ')]}': depth -= 1
            elif ch == ',' and depth == 0: at.append(i + 1)
        for a in at:
            nm = re.match(r'\s*(\w+)\s*=', line[a:])
            if nm: names.append(nm.group(1))
    src = re.sub(r'^export \{ [\w, ]+ \};\n', '', src, flags=re.M)
    src = re.sub(r'^export (async function|function|const) ', r'\1 ', src, flags=re.M)
    if re.search(r'^export ', src, flags=re.M): sys.exit('an export this script does not know how to strip')
    names = list(dict.fromkeys(names))
    head = ('// GENERATED by scripts/people_bundle.py from docs/prototypes/levelup/people.js (Session 1193, card F4). Do not edit:\n'
            '// change people.js and run the script again. The new look only (index.html\'s chooser loads it after three.js 0.170).\n'
            f"var HB=(function(){{'use strict';\nconst MH_PACK_SHA256='{pack_sha}';\n"
            'function mhBuffer(){const s=atob(MH_PACK.b64),n=s.length,u=new Uint8Array(n);for(let i=0;i<n;i++)u[i]=s.charCodeAt(i);MH_PACK.b64=null;return u.buffer;}\n')
    foot = '\nreturn {' + ','.join(names) + ',MH_PACK_SHA256,get PACK(){return PACK;}};\n})();\n'
    return head + src + foot


def pack_js(d):
    ix = json.load(open(os.path.join(d, 'pack.json'), encoding='utf-8'))
    raw = open(os.path.join(d, 'pack.bin'), 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()
    body = ('// GENERATED by scripts/people_bundle.py from mh_pack.py\'s pack (MakeHuman\'s base body, targets and skeleton, CC0).\n'
            f'// SHA-256 of the binary: {sha}. The new look only.\n'
            'var MH_PACK={ix:' + json.dumps(ix, separators=(',', ':')) + ",b64:'" + base64.b64encode(raw).decode('ascii') + "'};\n")
    return body, sha


def committed_sha():
    if not os.path.exists(PACK_OUT): return 'none'
    with open(PACK_OUT, encoding='utf-8') as f:
        for _ in range(3):
            m = re.search(r'SHA-256 of the binary: (\w+)', f.readline())
            if m: return m.group(1)
    return 'none'


def main():
    a = sys.argv[1:]
    src = open(SRC, encoding='utf-8').read()
    if '--check' in a:
        want = bundle(src, committed_sha())
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if want != have:
            sys.exit('vendor/people.builder.js is stale: run python3 scripts/people_bundle.py')
        print('vendor/people.builder.js matches people.js'); return
    d = a[a.index('--pack') + 1] if '--pack' in a else os.path.join(ROOT, 'docs', 'prototypes', 'levelup', 'mh')
    sha = committed_sha()
    if os.path.exists(os.path.join(d, 'pack.bin')):
        body, sha = pack_js(d)
        open(PACK_OUT, 'w', encoding='utf-8', newline='\n').write(body)
        print(f'vendor/mh-pack.js: {len(body):,} bytes')
    out = bundle(src, sha)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(out)
    print(f'vendor/people.builder.js: {len(out):,} bytes')


if __name__ == '__main__':
    main()
